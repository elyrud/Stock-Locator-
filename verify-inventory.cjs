function boot(initial = {}, blocked = false, missing = [], writeBlocked = false) {
  const storage = {...initial};
  const nodes = {};
  const get = id => missing.includes(id) ? null : (nodes[id] ||= {value:'', textContent:'', innerHTML:'', style:{}, dataset:{}, classList:{add(){},remove(){},contains(){return false;}}, addEventListener(type,fn){this[type]=fn;}, focus(){}, scrollIntoView(){}, reset(){}});
  const events = {};
  const context = vm.createContext({window:{addEventListener(type,fn){events[type]=fn;}},document:{getElementById:get,addEventListener(){}}, localStorage:{getItem(key){if(blocked) throw Error('Blocked'); return storage[key] ?? null;},setItem(key,value){if(blocked || writeBlocked) throw Error('Blocked');storage[key]=value;}},setTimeout(){},confirm(){return true;}});
  vm.runInContext(source,context);
  return {context,storage,nodes,get,events,run:code=>vm.runInContext(code,context)};
}
